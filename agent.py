# 3. LANGGRAPH STATE DEFINITION
# ============================================================================

class AgentState(TypedDict):
    """The state shared across all nodes in the LangGraph pipeline."""
    messages: Annotated[Sequence[BaseMessage], add_messages]
    query: str
    retrieved_docs: List[Document]
    retrieved_context: str
    property_metadata: List[Dict[str, Any]]
    final_answer: str


# ============================================================================
# 4. LANGGRAPH NODES
# ============================================================================

SYSTEM_PROMPT = """You are **PropPilot AI**, an elite and knowledgeable real estate advisory intelligence system.
Your mission is to help users find their ideal homes, villas, and apartments based strictly on verified property listings in your database.

Guidelines:
1. **Grounded In Data**: Base your recommendations primarily on the retrieved property listings provided below. Mention property titles, locations, price points, bedroom/bathroom configurations, and distinctive amenities directly from the data.
2. **Actionable & Structured**: Format your response with clear markdown headings, bulleted property highlights, and personalized reasoning for why each listing fits the user's inquiry.
3. **Honest & Helpful**: If no exact match exists for a specific parameter, suggest the closest available properties from the context.
4. **Follow-up Next Steps**: Conclude with a helpful question or suggested next steps (e.g., scheduling a virtual viewing, filtering by price, or exploring nearby neighborhoods).

Retrieved Property Database Listings:
{context}
"""

def extract_query(messages: Sequence[BaseMessage]) -> str:
    """Extracts the latest user query from the messages sequence."""
    for msg in reversed(messages):
        if isinstance(msg, HumanMessage) or getattr(msg, "type", "") == "human":
            return msg.content if isinstance(msg.content, str) else str(msg.content)
    return ""


def parse_property_doc(doc: Document) -> Dict[str, Any]:
    """Helper to parse key property metadata from a CSVLoader document."""
    data = {"raw": doc.page_content}
    lines = doc.page_content.split("\n")
    for line in lines:
        if ":" in line:
            parts = line.split(":", 1)
            key = parts[0].strip().lower().replace(" ", "_")
            val = parts[1].strip()
            data[key] = val
    return data


def retrieve_properties_node(state: AgentState) -> Dict[str, Any]:
    """
    Node 1: Retrieves the most relevant property documents from the FAISS vector database.
    """
    user_query = state.get("query") or extract_query(state.get("messages", []))
    if not user_query:
        user_query = "modern luxury home in UK"

    print(f"🔍 [retrieve_properties_node] Searching FAISS for: '{user_query}'")
    vectorstore = get_vectorstore()
    
    # Retrieve top 4 most relevant property chunks
    docs = vectorstore.similarity_search(user_query, k=4)
    print(f"   Found {len(docs)} matching property records.")

    # Format context string for the LLM
    context_chunks = []
    parsed_metadata = []
    for i, doc in enumerate(docs, 1):
        context_chunks.append(f"--- Property Listing #{i} ---\n{doc.page_content}")
        parsed_metadata.append(parse_property_doc(doc))

    retrieved_context = "\n\n".join(context_chunks)

    return {
        "query": user_query,
        "retrieved_docs": docs,
        "retrieved_context": retrieved_context,
        "property_metadata": parsed_metadata,
    }


def generate_recommendations_node(state: AgentState) -> Dict[str, Any]:
    """
    Node 2: Passes the retrieved properties and conversation history to the OpenRouter LLM.
    """
    retrieved_context = state.get("retrieved_context", "No property listings found.")
    messages = state.get("messages", [])

    system_message = SystemMessage(
        content=SYSTEM_PROMPT.format(context=retrieved_context)
    )

    prompt_messages = [system_message]
    for msg in messages:
        if isinstance(msg, (HumanMessage, AIMessage)):
            prompt_messages.append(msg)

    # If messages was empty or lacked HumanMessage, append the query
    if not any(isinstance(m, HumanMessage) for m in prompt_messages):
        prompt_messages.append(HumanMessage(content=state.get("query", "Find recommendations")))

    print(f"🤖 [generate_recommendations_node] Invoking LLM ({OPENROUTER_MODEL})...")
    llm = get_llm()

    try:
        response = llm.invoke(prompt_messages)
        answer_text = response.content if isinstance(response.content, str) else str(response.content)
    except Exception as e:
        print(f"⚠️ Primary model invocation failed: {e}. Trying fallback model 'openrouter/auto'...")
        try:
            fallback_llm = get_llm(model_name="openrouter/auto")
            response = fallback_llm.invoke(prompt_messages)
            answer_text = response.content if isinstance(response.content, str) else str(response.content)
        except Exception as fallback_err:
            answer_text = (
                f"I found matching properties in our database, but encountered a connection "
                f"issue with the OpenRouter API: {fallback_err}\n\n"
                f"Here are the top listings retrieved directly from the dataset:\n\n"
                f"{retrieved_context}"
            )

    return {
        "messages": [AIMessage(content=answer_text)],
        "final_answer": answer_text
    }


# ============================================================================
# 5. COMPILE LANGGRAPH PIPELINE
# ============================================================================

def build_proppilot_graph():
    """
    Builds and compiles the LangGraph StateGraph pipeline:
    START -> retrieve_properties -> generate_recommendations -> END
    """
    builder = StateGraph(AgentState)

    builder.add_node("retrieve_properties", retrieve_properties_node)
    builder.add_node("generate_recommendations", generate_recommendations_node)

    builder.add_edge(START, "retrieve_properties")
    builder.add_edge("retrieve_properties", "generate_recommendations")
    builder.add_edge("generate_recommendations", END)

    return builder.compile()


# Global compiled graph instance
proppilot_agent = build_proppilot_graph()


# ============================================================================
# 6. HIGH-LEVEL QUERY API
# ============================================================================

def run_query(query: str, history: Optional[List[Dict[str, str]]] = None) -> Dict[str, Any]:
    """
    Synchronous helper to execute a query turn through the LangGraph pipeline.
    
    :param query: The user's prompt (e.g., "Find luxury villas in London with pool")
    :param history: Optional list of past messages [{'role': 'user'|'assistant', 'content': '...'}]
    :return: Dict with 'answer', 'properties', and 'query'
    """
    messages: List[BaseMessage] = []
    if history:
        for item in history:
            role = item.get("role")
            content = item.get("content", "")
            if role == "user":
                messages.append(HumanMessage(content=content))
            elif role == "assistant":
                messages.append(AIMessage(content=content))

    messages.append(HumanMessage(content=query))

    initial_state: AgentState = {
        "messages": messages,
        "query": query,
        "retrieved_docs": [],
        "retrieved_context": "",
        "property_metadata": [],
        "final_answer": "",
    }

    final_state = proppilot_agent.invoke(initial_state)

    return {
        "answer": final_state.get("final_answer", ""),
        "properties": final_state.get("property_metadata", []),
        "query": query
    }


async def stream_query(query: str, history: Optional[List[Dict[str, str]]] = None):
    """
    Asynchronous generator yielding streamed tokens and tool events.
    """
    messages: List[BaseMessage] = []
    if history:
        for item in history:
            role = item.get("role")
            content = item.get("content", "")
            if role == "user":
                messages.append(HumanMessage(content=content))
            elif role == "assistant":
                messages.append(AIMessage(content=content))

    messages.append(HumanMessage(content=query))

    initial_state: AgentState = {
        "messages": messages,
        "query": query,
        "retrieved_docs": [],
        "retrieved_context": "",
        "property_metadata": [],
        "final_answer": "",
    }

    # Execute graph nodes and stream updates
    async for event in proppilot_agent.astream(initial_state):
        yield event


