def create_api_app():
    """Builds a FastAPI app with SSE streaming support for the React frontend."""
    from fastapi import FastAPI, Request
    from fastapi.middleware.cors import CORSMiddleware
    from fastapi.responses import StreamingResponse, JSONResponse
    from pydantic import BaseModel

    api = FastAPI(
        title="PropPilot LangGraph AI API",
        description="Real Estate Recommendation Agent with FAISS Vector Search & OpenRouter LLM",
        version="1.0.0"
    )

    api.add_middleware(
        CORSMiddleware,
        allow_origins=["*"],
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
    )

    class ChatInput(BaseModel):
        message: Optional[str] = None
        input: Optional[Dict[str, Any]] = None
        history: Optional[List[Dict[str, str]]] = None
        filters: Optional[Dict[str, Any]] = None

    @api.get("/health")
    def health_check():
        return {"status": "ok", "agent": "PropPilot", "model": OPENROUTER_MODEL}

    @api.post("/api/chat")
    def chat_endpoint(payload: ChatInput):
        # Support both payload formats ({ message } or { input: { messages: [...] } })
        user_message = payload.message
        history = payload.history or []
        if not user_message and payload.input:
            msgs = payload.input.get("messages", [])
            if msgs:
                user_message = msgs[-1].get("content", "")
                history = msgs[:-1]

        if not user_message:
            return JSONResponse({"error": "No message provided"}, status_code=400)

        result = run_query(user_message, history)
        return result

    @api.post("/api/chat/stream")
    @api.post("/stream")
    async def stream_endpoint(payload: ChatInput):
        """Streams Server-Sent Events (SSE) directly to the React frontend."""
        user_message = payload.message
        history = payload.history or []
        if not user_message and payload.input:
            msgs = payload.input.get("messages", [])
            if msgs:
                user_message = msgs[-1].get("content", "")
                history = msgs[:-1]

        if not user_message:
            user_message = "Find real estate recommendations in United Kingdom"

        async def event_generator():
            # Step 1: Run retrieval & emit matching property notification
            vectorstore = get_vectorstore()
            docs = vectorstore.similarity_search(user_message, k=4)
            retrieved_props = [parse_property_doc(d) for d in docs]
            
            # Emit tool call event
            yield f"data: {json.dumps({'tool_call': {'name': 'vector_search', 'args': {'query': user_message, 'found': len(docs)}}})}\n\n"
            await asyncio.sleep(0.05)

            # Step 2: Stream tokens from LLM
            llm = get_llm(streaming=True)
            system_message = SystemMessage(
                content=SYSTEM_PROMPT.format(
                    context="\n\n".join([f"Listing #{i+1}:\n{d.page_content}" for i, d in enumerate(docs)])
                )
            )
            prompt_msgs = [system_message, HumanMessage(content=user_message)]

            async for chunk in llm.astream(prompt_msgs):
                token = chunk.content if hasattr(chunk, "content") else str(chunk)
                if token:
                    yield f"data: {json.dumps({'token': token})}\n\n"

            # Step 3: Complete event with property metadata
            yield f"data: {json.dumps({'done': True, 'properties': retrieved_props})}\n\n"

        return StreamingResponse(event_generator(), media_type="text/event-stream")

    # ========================================================================
    # CROSS-DEVICE REAL-TIME STATE SYNCHRONIZATION
    # ========================================================================
    from fastapi import WebSocket, WebSocketDisconnect
    import time

    STATE_FILE = "synced_global_state.json"

    def load_persisted_state():
        if os.path.exists(STATE_FILE):
            try:
                with open(STATE_FILE, "r") as f:
                    return json.load(f)
            except Exception:
                pass
        return {
            "activeFilters": {},
            "messages": [],
            "savedPropertyIds": [],
            "currentMapLocation": {"lat": 12.9141, "lng": 74.8560, "zoom": 12},
            "selectedPropertyId": None,
            "role": "user",
            "activeTab": "chat",
            "updatedAt": None,
            "sourceDevice": "server_init"
        }

    def save_persisted_state(state):
        try:
            with open(STATE_FILE, "w") as f:
                json.dump(state, f, indent=2)
        except Exception as e:
            print(f"Error saving persisted state: {e}")

    class SyncConnectionManager:
        def __init__(self):
            self.active_connections: Dict[str, List[WebSocket]] = {}

        async def connect(self, websocket: WebSocket, session_id: str):
            await websocket.accept()
            if session_id not in self.active_connections:
                self.active_connections[session_id] = []
            self.active_connections[session_id].append(websocket)

        def disconnect(self, websocket: WebSocket, session_id: str):
            if session_id in self.active_connections:
                if websocket in self.active_connections[session_id]:
                    self.active_connections[session_id].remove(websocket)
                if not self.active_connections[session_id]:
                    del self.active_connections[session_id]

        async def broadcast(self, message: dict, session_id: str, exclude_socket: Optional[WebSocket] = None):
            if session_id in self.active_connections:
                for connection in list(self.active_connections[session_id]):
                    if connection != exclude_socket:
                        try:
                            await connection.send_json(message)
                        except Exception:
                            self.disconnect(connection, session_id)

    sync_manager = SyncConnectionManager()
    current_global_state = load_persisted_state()

    @api.get("/api/sync/state")
    def get_sync_state(sessionId: str = "default_session"):
        return {"sessionId": sessionId, "state": current_global_state}

    @api.post("/api/sync/state")
    async def post_sync_state(payload: Dict[str, Any], sessionId: str = "default_session"):
        nonlocal current_global_state
        state_update = payload.get("state", payload)
        source = payload.get("source", "rest_client")
        current_global_state.update(state_update)
        current_global_state["updatedAt"] = time.time()
        current_global_state["sourceDevice"] = source
        save_persisted_state(current_global_state)

        await sync_manager.broadcast({
            "type": "STATE_BROADCAST",
            "state": current_global_state,
            "source": source,
            "timestamp": current_global_state["updatedAt"]
        }, session_id=sessionId)

        return {"status": "ok", "synced": True, "state": current_global_state}

    @api.websocket("/ws/sync/{session_id}")
    async def websocket_sync_endpoint(websocket: WebSocket, session_id: str):
        nonlocal current_global_state
        await sync_manager.connect(websocket, session_id)
        try:
            # Send current synchronized state upon connection
            await websocket.send_json({
                "type": "INITIAL_STATE",
                "state": current_global_state,
                "clientCount": len(sync_manager.active_connections.get(session_id, []))
            })

            while True:
                data = await websocket.receive_json()
                msg_type = data.get("type", "STATE_UPDATE")
                payload_state = data.get("payload", {})
                source = data.get("source", "unknown_device")

                current_global_state.update(payload_state)
                current_global_state["updatedAt"] = time.time()
                current_global_state["sourceDevice"] = source
                save_persisted_state(current_global_state)

                # Real-time broadcast to all other devices (laptop <-> phone)
                await sync_manager.broadcast({
                    "type": "REMOTE_STATE_UPDATED",
                    "state": current_global_state,
                    "source": source,
                    "timestamp": current_global_state["updatedAt"]
                }, session_id=session_id, exclude_socket=websocket)

        except WebSocketDisconnect:
            sync_manager.disconnect(websocket, session_id)
        except Exception:
            sync_manager.disconnect(websocket, session_id)

    return api


