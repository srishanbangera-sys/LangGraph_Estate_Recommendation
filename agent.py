# 1. VECTOR STORE LOADER
# ============================================================================

_vectorstore_cache: Optional[FAISS] = None

def get_vectorstore(index_dir: str = FAISS_INDEX_DIR, index_name: str = FAISS_INDEX_NAME) -> FAISS:
    """
    Loads and caches the FAISS vector store generated by proppilot_rag_ingestion.ipynb.
    Checks multiple search paths to find index.faiss and index.pkl gracefully.
    """
    global _vectorstore_cache
    if _vectorstore_cache is not None:
        return _vectorstore_cache

    candidate_dirs = [
        index_dir,
        os.path.dirname(os.path.abspath(__file__)),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "faiss_index"),
        "./faiss_index",
        "."
    ]

    resolved_dir = None
    for d in candidate_dirs:
        faiss_file = os.path.join(d, f"{index_name}.faiss")
        pkl_file = os.path.join(d, f"{index_name}.pkl")
        if os.path.isfile(faiss_file) and os.path.isfile(pkl_file):
            resolved_dir = d
            break

    if not resolved_dir:
        raise FileNotFoundError(
            f"Could not find '{index_name}.faiss' and '{index_name}.pkl'. "
            f"Searched in: {candidate_dirs}"
        )

    print(f"📦 [PropPilot RAG] Loading FAISS index '{index_name}' from: {resolved_dir}")
    embeddings = HuggingFaceEmbeddings(model_name=EMBEDDING_MODEL_NAME)
    
    _vectorstore_cache = FAISS.load_local(
        folder_path=resolved_dir,
        embeddings=embeddings,
        index_name=index_name,
        allow_dangerous_deserialization=True  # safe: locally generated index
    )
    return _vectorstore_cache


# ============================================================================
# 2. OPENROUTER LLM FACTORY
# ============================================================================

def get_llm(model_name: str = OPENROUTER_MODEL, temperature: float = 0.3, streaming: bool = False) -> ChatOpenAI:
    """
    Initializes a ChatOpenAI client connected to OpenRouter API.
    """
    return ChatOpenAI(
        model=model_name,
        openai_api_key=OPENROUTER_API_KEY,
        openai_api_base=OPENROUTER_BASE_URL,
        temperature=temperature,
        streaming=streaming,
        default_headers={
            "HTTP-Referer": "https://github.com/srishanbangera-sys/LangGraph_Estate_Recommendation",
            "X-Title": "PropPilot Real Estate AI",
        }
    )


