def interactive_cli():
    """Runs an interactive command-line interface for immediate testing."""
    print("=" * 65)
    print("  🏡 PropPilot — LangGraph Real Estate Recommendation Agent")
    print("=" * 65)
    print(f"  • LLM:         {OPENROUTER_MODEL} via OpenRouter")
    print(f"  • Embeddings:  {EMBEDDING_MODEL_NAME}")
    print(f"  • Vectorstore: FAISS ({FAISS_INDEX_NAME}.faiss + {FAISS_INDEX_NAME}.pkl)")
    print("=" * 65)
    print("  Type your property questions below (or 'exit' to quit).\n")

    # Pre-warm vectorstore
    try:
        get_vectorstore()
        print("✅ FAISS vector database loaded successfully.\n")
    except Exception as e:
        print(f"❌ Failed to load FAISS index: {e}\n")
        return

    chat_history: List[Dict[str, str]] = []

    while True:
        try:
            user_input = input("\n👤 You: ").strip()
            if not user_input:
                continue
            if user_input.lower() in ("exit", "quit", "q"):
                print("\n👋 Goodbye! Happy property hunting.\n")
                break

            print("\n🤖 PropPilot is searching vector database & generating recommendations...")
            result = run_query(user_input, chat_history)

            print("\n" + result["answer"])

            # Store in history
            chat_history.append({"role": "user", "content": user_input})
            chat_history.append({"role": "assistant", "content": result["answer"]})

        except KeyboardInterrupt:
            print("\n\nSession terminated by user.")
            break
        except Exception as e:
            print(f"\n⚠️ Error: {e}")


